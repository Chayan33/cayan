// p=pick up; d=deliver; t=talk; i=inspect; r=repair; c=clean; w=watch; $=pay; s=signal.
const actions = {
  p: "pickup",
  d: "deliver",
  t: "talk",
  i: "inspect",
  r: "repair",
  c: "clean",
  w: "wait",
  $: "pay",
  s: "signal",
  b: "deposit",
} as const;
function route(spec: string): Objective[] {
  return spec.split("|").map((part) => {
    const [code, place, text, value] = part.split("~");
    const action = actions[code as keyof typeof actions];
    return {
      action,
      place,
      text,
      amount:
        action === "pay" || action === "deposit"
          ? Number(value || 100)
          : undefined,
      duration: ["repair", "clean", "wait", "inspect", "signal"].includes(
        action,
      )
        ? Number(value || 3)
        : undefined,
    };
  });
}
