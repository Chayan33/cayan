export const quests: Quest[] = groups.flatMap(([prefix, category, seeds]) =>
  seeds.map(([title, giver, story, spec, reward, minutes], i) => ({
    id: `${prefix}-${i + 1}`,
    title,
    giver,
    story,
    category,
    level: prefix === "risk" ? Math.floor(i / 6) + 2 : Math.floor(i / 4) + 1,
    reward: reward || 200,
    xp: 60 + i * 20,
    risk: prefix === "risk" ? Math.min(85, 22 + i * 3) : 0,
    minutes,
    requires: i ? [`${prefix}-${i}`] : prefix === "risk" ? ["legal-1"] : [],
    stages: route(spec),
    repeatable: prefix === "legal" || prefix === "coop",
    failure: minutes
      ? `${minutes} dakikalık süre biterse veya yakalanırsan iş iptal olur; tekrar başlatabilirsin.`
      : "Yakalanırsan iş iptal olur. Eşyayı bırakırsan aynı yerden geri alabilirsin.",
  })),
);
export const questById = Object.fromEntries(quests.map((q) => [q.id, q]));
export const levelFromXP = (xp: number) =>
  1 + Math.floor(Math.sqrt(Math.max(0, xp) / 160));
export function available(
  q: Quest,
  completed: string[],
  xp: number,
  players = 1,
) {
  return (
    q.level <= levelFromXP(xp) &&
    q.requires.every((id) => completed.includes(id)) &&
    (q.category !== "Birlikte" || players >= 2)
  );
}
